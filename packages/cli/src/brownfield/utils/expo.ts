import { spawn, spawnSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';

import { logger } from '@rock-js/tools';

import { isExpoProject } from './project.js';

type ExpoPlatform = 'ios' | 'android';

async function spawnCommand({
  command,
  args,
  cwd,
}: {
  command: string;
  args: string[];
  cwd: string;
}) {
  await new Promise<void>((resolve, reject) => {
    const child = spawn(command, args, {
      cwd,
      env: process.env,
      stdio: 'inherit',
    });

    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) {
        resolve();
      } else {
        reject(
          new Error(
            `Command "${command} ${args.join(' ')}" failed with exit code ${code ?? 'unknown'}.`
          )
        );
      }
    });
  });
}

function getNpxCommand() {
  return process.platform === 'win32' ? 'npx.cmd' : 'npx';
}

function isGitIgnored(targetPath: string): boolean {
  // `git check-ignore` exits 0 when ignored, 1 when not, 128 outside a repo.
  const result = spawnSync('git', ['check-ignore', '-q', targetPath], {
    cwd: path.dirname(targetPath),
    stdio: 'ignore',
  });
  if (result.status !== 0 && result.status !== 1) {
    logger.warn(
      `Couldn't check with git whether ${path.basename(targetPath)}/ is gitignored, so it's treated as committed and expo prebuild is skipped. If this project uses Continuous Native Generation, run \`npx expo prebuild\` before packaging.`
    );
  }
  return result.status === 0;
}

/**
 * Whether the platform's native project is generated by `expo prebuild` (Continuous Native
 * Generation) rather than maintained by hand. A bare React Native app that installed Expo modules
 * commits its native directories; running prebuild there would wipe them (including the
 * brownfield library module), so prebuild only runs when the directory is missing or gitignored.
 */
export function usesContinuousNativeGeneration(
  projectRoot: string,
  platform: ExpoPlatform
): boolean {
  const nativeDir = path.join(projectRoot, platform);
  return !fs.existsSync(nativeDir) || isGitIgnored(nativeDir);
}

export async function runExpoPrebuildIfNeeded({
  projectRoot,
  platform,
}: {
  projectRoot: string;
  platform: ExpoPlatform;
}) {
  if (!isExpoProject(projectRoot)) {
    return false;
  }

  if (!usesContinuousNativeGeneration(projectRoot, platform)) {
    logger.info(
      `Expo modules detected in a project with a committed ${platform} directory. Skipping expo prebuild.`
    );
    return false;
  }

  logger.info(
    `Expo project detected. Running expo prebuild for ${platform}...`
  );

  const args = ['expo', 'prebuild', '--platform', platform];
  if (platform === 'ios') {
    args.push('--no-install');
  }

  await spawnCommand({
    command: getNpxCommand(),
    args,
    cwd: projectRoot,
  });

  return true;
}
